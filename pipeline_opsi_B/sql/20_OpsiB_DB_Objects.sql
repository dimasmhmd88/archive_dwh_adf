                     @TableLogId = @TableLogId, @TableConfigId = @TableConfigId, @StartTime = @Now,
                     @ErrorCode = 'ERR-LCK-01', @ErrorMessage = @ErrMsg;

                IF OBJECT_ID(N'tempdb..#RetOut_usp_BeginTable') IS NULL
